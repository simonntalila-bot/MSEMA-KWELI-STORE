const lang = ref(localStorage.getItem('msemakwel_lang') || 'sw')

export function useI18n() {
    const currentLang = computed(() => lang.value)
    const langFlag = computed(() => lang.value === 'sw' ? '\uD83C\uDDFF\uD83C\uDDFA' : '\uD83C\uDDEC\uD83C\uDDE7')
    const langLabel = computed(() => lang.value === 'sw' ? 'SW' : 'EN')

    function t(key) {
        return translations[lang.value]?.[key] || translations.en[key] || key
    }

    function toggleLang() {
        lang.value = lang.value === 'sw' ? 'en' : 'sw'
        localStorage.setItem('msemakwel_lang', lang.value)
    }

    return { currentLang, langFlag, langLabel, t, toggleLang }
}
